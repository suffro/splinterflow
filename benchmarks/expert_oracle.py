def load_target(raw_config: dict, layer_name: str, device):
    """The target layer's experts (fused as transformers fuses them), shared experts, the final norm and the LM head, read
    from the published checkpoint (safetensors) as stored, with each expert's offsets in its file."""
    from huggingface_hub import hf_hub_download
    from safetensors import safe_open

    from awpmi.oracle.experts import ExpertOffsets
    from awpmi.storage.layout import safetensors_segments

    runtime = phase4b()
    model_config = raw_config["model"]
    adapter = runtime.load_adapter(model_config)
    repository, revision = model_config["repository"], model_config["revision"]
    index = json.loads(Path(hf_hub_download(repository, "model.safetensors.index.json", revision=revision, local_files_only=True)).read_text(encoding="utf-8"))
    weight_map = index["weight_map"]
    templates = {
        "gate": f"{layer_name}." + adapter.EXPERT_LAYOUT["gate_up_proj"][0],
        "up": f"{layer_name}." + adapter.EXPERT_LAYOUT["gate_up_proj"][1],
        "down": f"{layer_name}." + adapter.EXPERT_LAYOUT["down_proj"][0],
    }
    shared_prefix = f"{layer_name}.{adapter.SHARED_SUFFIX}"
    names = {"lm_head": f"{adapter.LM_HEAD}.weight", "norm": f"{adapter.FINAL_NORM}.weight"}
    names.update({f"shared_{p}": f"{shared_prefix}.{p}_proj.weight" for p in ("gate", "up", "down")})
    tensors, handles, segments = {}, {}, {}

    def read(name: str) -> torch.Tensor:
        file = weight_map[name]
        if file not in handles:
            path = hf_hub_download(repository, file, revision=revision, local_files_only=True)
            handles[file] = safe_open(path, framework="pt", device="cpu")
            segments[file] = safetensors_segments(path, file)
        return handles[file].get_tensor(name)

    for key, name in names.items():
        tensors[key] = read(name).to(device)
    experts = 0
    while templates["gate"].format(expert=experts) in weight_map:
        experts += 1
    stacks = {matrix: [] for matrix in templates}
    offsets = {}
    for expert in range(experts):
        places = {}
        for matrix, template in templates.items():
            name = template.format(expert=expert)
            stacks[matrix].append(read(name))
            places[matrix] = segments[weight_map[name]][name].offset
        offsets[expert] = ExpertOffsets(weight_map[templates["gate"].format(expert=expert)], places["gate"], places["up"], places["down"])
    gate_up = torch.cat([torch.stack(stacks["gate"]), torch.stack(stacks["up"])], dim=1).contiguous().to(device)  # MergeModulelist + Concatenate
    down = torch.stack(stacks["down"]).contiguous().to(device)
    handles.clear()
    return gate_up, down, tensors, offsets


def row_digests(tensor: torch.Tensor) -> list[str]:
    import hashlib

    data = tensor.detach().contiguous().view(torch.uint8).reshape(tensor.shape[0], -1).cpu().numpy()
    return [hashlib.sha256(data[row].tobytes()).hexdigest() for row in range(data.shape[0])]


def finite(value: float) -> float | None:
    return float(value) if math.isfinite(value) else None


def cell_record(result, tier: str, strategy, bound: str, ordering: str) -> dict:
    record = {"tier": tier, "strategy": strategy.name, "family": strategy.family, "bound": bound, "ordering": ordering}
    record.update({key: getattr(result, key) for key in (
        "would_certify", "certified", "winner", "candidate_is_reference", "evaluations", "full_checks", "checkpoint", "bytes",
        "fraction", "units_read", "states", "physical", "violations", "reused_ceiling",
    )})
    record["margin"] = finite(result.margin)
    record["unread_term"] = finite(result.unread_term)
    record["per_expert_fraction"] = [round(value, 9) for value in result.per_expert_fraction]
    return record


def shard_prompts(prompts: list[dict], shard: int, shards: int) -> set[int]:
    """The prompt ids of shard `shard` of `shards`: contiguous blocks of the prompt list."""
    size = math.ceil(len(prompts) / shards)
    return {p["prompt_id"] for p in prompts[shard * size : (shard + 1) * size]}


def run_oracle(raw_config: dict, output: Path, prompts: list[dict], part: str, shard: int) -> int:
    """`part` "main": every sample's checks and ceilings, the certified and rn_even tiers' cells; "real": the real tier's
    cells on the configured decode steps. Each part runs in shards (blocks of prompts, `oracle.shards`), one process
    each, so that no stage runs longer than the harness allows; their outputs are read in shard order."""
    from safetensors.torch import load_file
    from transformers.activations import ACT2FN
    from transformers.models.deepseek_v3.modeling_deepseek_v3 import DeepseekV3MLP, DeepseekV3RMSNorm

    from awpmi.oracle import experts as oracle

    runtime = phase4b()
    device = torch.device("cuda", torch.cuda.current_device())
    settings = raw_config["oracle"]
    report: dict = {"timings_ms": {}}
    failures: list[dict] = []
    started = time.perf_counter()
    capture = load_file(str(output / "capture.safetensors"))
    records = {(r["prompt_id"], r["step"]): r for r in read_jsonl(output / "capture.jsonl.gz")}
    layer_name = json.loads((output / "capture_stage.json").read_text(encoding="utf-8"))["target_layer"]
    gate_up, down, tensors, offsets = load_target(raw_config, layer_name, device)
    report["timings_ms"]["load"] = (time.perf_counter() - started) * 1e3
    # The weights are the reference's: every expert row's sha256 equals the one the Phase 4B reference loaded.
    expected = json.loads((REPO_ROOT / raw_config["phase4b_reference"] / "reference_rows.json").read_text(encoding="utf-8"))
    experts_name = f"{layer_name}.mlp.experts"
    report["weights_equal_reference_rows"] = (
        row_digests(gate_up) == expected[f"{experts_name}.gate_up_proj"] and row_digests(down) == expected[f"{experts_name}.down_proj"]
    )
    if not report["weights_equal_reference_rows"]:
        failures.append({"kind": "weights", "layer": layer_name})
        (output / "failure.json").write_text(json.dumps(failures, indent=2), encoding="utf-8")
        return 1
    config = __import__("transformers").AutoConfig.from_pretrained(raw_config["model"]["repository"], revision=raw_config["model"]["revision"])
    act_fn = ACT2FN[config.hidden_act]
    layer = oracle.ExpertLayer(gate_up, down, act_fn)
    norm = DeepseekV3RMSNorm(config.hidden_size, eps=config.rms_norm_eps).to(device=device, dtype=torch.bfloat16)
    norm.weight.data.copy_(tensors["norm"])
    shared = DeepseekV3MLP(config, intermediate_size=config.moe_intermediate_size * config.n_shared_experts).to(device=device, dtype=torch.bfloat16)
    for projection in ("gate", "up", "down"):
        getattr(shared, f"{projection}_proj").weight.data.copy_(tensors[f"shared_{projection}"])
    lm_weight, gain = tensors["lm_head"], tensors["norm"]
    strategies = oracle.strategies(settings["page_rows"], settings["specs"])
    slots = capture["top_k_index"].shape[1]
    # A token a strategy never certifies costs its whole schedule; its modelled I/O, on the first sample's experts.
    first_experts = capture["top_k_index"][0].tolist()
    everything = oracle.ExpertStates.filled(layer, slots, device, oracle.EXACT, columns=True)
    report["strategies"] = {
        s.name: {
            "family": s.family, "page_rows": s.page_rows, "spec": s.spec, "storage_multiplier": s.storage_multiplier(layer),
            "fallback_bytes": s.fallback_bytes(layer, slots), "metadata_bytes": s.metadata_bytes(layer, slots),
            "fallback_physical": oracle.physical_estimate(s, layer, first_experts, everything, offsets, fallback=True),
        }
        for s in strategies
    }
    report["expert_bytes"] = layer.expert_bytes
    report["routed_bytes"] = layer.expert_bytes * capture["top_k_index"].shape[1]
    real_steps = set(int(s) for s in settings["cell_steps"]["real"])
    budget_step = float(settings["budget_step"])
    oracle.Certifier.partial_columns = int(settings["partial_columns"])
    name = "samples" if part == "main" else "real_cells"
    count = capture["x"].shape[0]
    shards = int(settings["shards"][part])
    mine = shard_prompts(prompts, shard, shards)
    report["shard"] = {"index": shard, "of": shards, "prompts": sorted(mine)}
    started = time.perf_counter()

    def fail(kind: str, entry: dict) -> None:
        failures.append({"kind": kind, **entry})
        raise HardFailure

    try:
        with JsonlWriter(output / f"{name}.{shard}.jsonl.gz") as log:
            for n in range(count):
                prompt_id, step = int(capture["prompt_id"][n]), int(capture["step"][n])
                if prompt_id not in mine or (part == "real" and step not in real_steps):
                    continue
                sample_started = time.perf_counter()
                tensors_n = {key: capture[key][n].to(device) for key in ("x", "r", "S", "R", "m", "y", "h", "top_k_weights")}
                sample = oracle.decode_sample(layer, tensors_n["x"], tensors_n["r"], tensors_n["S"], capture["top_k_index"][n].tolist(),
                                              tensors_n["top_k_weights"], norm, lm_weight)
                captured = records[(prompt_id, step)]
                with torch.inference_mode():
                    shared_output = shared(tensors_n["x"].view(1, 1, -1)).reshape(-1)
                checks = {key: bool(torch.equal(sample.reference[key], tensors_n[key])) for key in ("R", "m", "y", "h")}
                checks["shared"] = bool(torch.equal(shared_output, tensors_n["S"]))
                checks["logits"] = runtime.logits_sha256(sample.reference["logits"]) == captured["logits_sha256"]
                checks["token"] = sample.token == captured["token"]
                if not all(checks.values()):
                    fail("reference", {"prompt_id": prompt_id, "step": step, "checks": checks})
                weights = oracle.SampleWeights(layer, sample.experts)
                logits = sample.reference["logits"].to(torch.float32)
                gap = float(logits[sample.token] - logits[sample.runner_up])
                record = {
                    "prompt_id": prompt_id, "step": step, "length": next(p["length"] for p in prompts if p["prompt_id"] == prompt_id),
                    "token": sample.token, "runner_up": sample.runner_up, "gap": gap, "experts": list(sample.experts),
                    "weights": [float(w) for w in sample.weights], "checks": checks,
                }
                tiers = tuple(settings["ceilings"]) if part == "main" else ("real",)
                record["ceilings"], record["cells"] = {}, []
                for tier_name in tiers:
                    arithmetic = oracle.ARITHMETIC[tier_name]
                    certifier = oracle.Certifier(lm_weight, gain, sample.reference["logits"], arithmetic, near=int(settings["near_rows"]),
                                                 chunk_rows=int(settings["chunk_rows"]))
                    outcome, bounds, violations = oracle.ceiling(sample, weights, arithmetic, certifier, gain, norm.variance_epsilon)
                    ceiling = {
                        "would_certify": outcome.certified, "certified": outcome.certified and arithmetic.certifies,
                        "candidate_is_reference": outcome.candidate == sample.token, "margin": finite(outcome.margin),
                        "near_failed": outcome.near_failed, "unsettled": outcome.unsettled, "full_checks": outcome.full_checks,
                        "terms": {key: finite(value) for key, value in outcome.terms.items()}, "violations": violations,
                        "scale_lower": None if bounds.norm is None else bounds.norm.scale_lower,
                    }
                    if part == "main":
                        record["ceilings"][tier_name] = ceiling
                    if arithmetic.certifies and sum(violations.values()):
                        fail("enclosure", {"prompt_id": prompt_id, "step": step, "tier": tier_name, "violations": violations})
                    if ceiling["certified"] and not ceiling["candidate_is_reference"]:
                        fail("certified_mismatch", {"prompt_id": prompt_id, "step": step, "tier": tier_name})
                    if not outcome.certified or tier_name not in settings["cells"]:
                        continue  # every cell falls back: partial knowledge never certifies what full knowledge does not
                    if (part == "main") == (tier_name == "real"):
                        continue  # the real tier's cells run in their own stage
                    steps_of_tier = settings.get("cell_steps", {}).get(tier_name)
                    if steps_of_tier is not None and step not in steps_of_tier:
                        continue  # this tier's cells run on its configured decode steps only
                    for strategy in strategies:
                        for bound_name, ordering_name in settings["cells"][tier_name]:
                            result = oracle.run_cell(
                                sample, weights, strategy, arithmetic, oracle.BoundTier(bound_name), oracle.Ordering(ordering_name),
                                certifier, budget_step, gain, norm.variance_epsilon, offsets, complete=outcome,
                            )
                            cell = cell_record(result, tier_name, strategy, bound_name, ordering_name)
                            record["cells"].append(cell)
                            if arithmetic.certifies and bound_name == "realistic" and sum(result.violations.values()):
                                fail("enclosure", {"prompt_id": prompt_id, "step": step, "strategy": strategy.name, "violations": result.violations})
                            if result.certified and result.winner != sample.token:
                                fail("certified_mismatch", {"prompt_id": prompt_id, "step": step, "strategy": strategy.name})
                record["timings_ms"] = {"sample": (time.perf_counter() - sample_started) * 1e3}
                log.write(record)
                if n % 16 == 0:
                    print(f"oracle {part}: sample {n}/{count} ({prompt_id}, {step}) {(time.perf_counter() - started):.0f}s", flush=True)
    except HardFailure:
        pass
    report["timings_ms"][part] = (time.perf_counter() - started) * 1e3
    report["peak_device_bytes"] = torch.cuda.max_memory_allocated(device)
    (output / f"oracle_{part}_{shard}_stage.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    if failures:
        path = output / "failure.json"
        existing = json.loads(path.read_text(encoding="utf-8")) if path.exists() else []
        path.write_text(json.dumps(existing + failures, indent=2), encoding="utf-8")
    return 1 if failures else 0


