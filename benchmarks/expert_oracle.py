def target_layer_name(model, adapter, target: str) -> str:
    """The decoder layer that holds the target MoE block ("last": the last experts module's layer)."""
    from awpmi.models.moe import find_expert_modules

    names = [m.name[: -len(adapter.EXPERTS_SUFFIX) - 1] for m in find_expert_modules(model)]
    if target == "last":
        return names[-1]
    if target not in names:
        raise ValueError(f"{target} is not a MoE layer")
    return target


# Capture


class TargetCapture:
    """The target MoE layer at the last position of one step: the oracle's inputs and the reference's values.

    x, the router's choice and weights and R come from the experts call itself; r is the input of the
    post-attention norm (the residual the MoE block's output is added to); S, m, y and h are the
    outputs of the shared experts, the MoE block, the decoder layer and the final norm.
    """

    def __init__(self, model, adapter, layer: str) -> None:
        self.layer = layer
        self.experts_module = f"{layer}.{adapter.EXPERTS_SUFFIX}"
        get = model.get_submodule
        self.handles = [
            get(f"{layer}.{adapter.RESIDUAL_NORM_SUFFIX}").register_forward_pre_hook(self._input("r")),
            get(f"{layer}.{adapter.SHARED_SUFFIX}").register_forward_hook(self._output("S")),
            get(f"{layer}.{adapter.BLOCK_SUFFIX}").register_forward_hook(self._output("m")),
            get(layer).register_forward_hook(self._output("y")),
            get(adapter.FINAL_NORM).register_forward_hook(self._output("h")),
        ]
        self.clear()

    def clear(self) -> None:
        self.values: dict[str, torch.Tensor] = {}

    @staticmethod
    def _last(tensor: torch.Tensor) -> torch.Tensor:
        return tensor.detach().reshape(-1, tensor.shape[-1])[-1].clone().cpu()

    def _input(self, key: str):
        def hook(module, args):
            self.values[key] = self._last(args[0])

        return hook

    def _output(self, key: str):
        def hook(module, args, output):
            self.values[key] = self._last(output[0] if isinstance(output, tuple) else output)

        return hook

    def on_call(self, call) -> None:
        if call.module != self.experts_module:
            return
        self.values["x"] = self._last(call.hidden_states)
        self.values["R"] = self._last(call.output)
        self.values["top_k_index"] = call.top_k_index.detach()[-1].clone().cpu()
        self.values["top_k_weights"] = call.top_k_weights.detach()[-1].clone().cpu()

    def remove(self) -> None:
        for handle in self.handles:
            handle.remove()

    def complete(self) -> dict[str, torch.Tensor]:
        missing = [key for key in (*TARGET_TENSORS, "top_k_index", "top_k_weights") if key not in self.values]
        if missing:
            raise RuntimeError(f"target layer not observed: {missing}")
        return dict(self.values)


def run_capture(raw_config: dict, output: Path, prompts: list[dict]) -> int:
    from safetensors.torch import save_file

    from awpmi.materialization.backend import MaterializationBackend
    from awpmi.materialization.weights import ExpertStore, WeightStore
    from awpmi.models.checkpoint import checkpoint_sources, load_model_without_experts
    from awpmi.models.moe import StreamedExperts, groups_from_pack
    from awpmi.storage.fileio import process_memory
    from awpmi.storage.pack import open_pack, sha256_file_direct
    from awpmi.streaming.streamer import PageStreamer

    runtime = phase4b()
    model_config, storage = raw_config["model"], raw_config["storage"]
    adapter = runtime.load_adapter(model_config)
    profile = adapter.REFERENCE_PROFILE
    device = torch.device("cuda", torch.cuda.current_device())
    dtype = DTYPES[model_config["dtype"]]
    steps = int(raw_config["prompts"]["decode_steps"])
    time.sleep(float(raw_config["timing"]["settle_seconds"]))
    report: dict = {"timings_ms": {}, "memory": {"start": process_memory()}}
    total = torch.cuda.get_device_properties(device).total_memory
    budget = int(raw_config["gpu_budget_bytes"])
    torch.cuda.set_per_process_memory_fraction(budget / total, device)
    report.update(gpu_total_bytes=total, gpu_budget_bytes=budget)
    failures: list[dict] = []

    def fail(kind: str, entry: dict) -> None:
        failures.append({"kind": kind, **entry})
        raise HardFailure

    # The published files, before anything else reads them (direct reads; the index refers to the expert files, the
    # others hold the embeddings, the dense layer, the norms and the LM head).
    skip = bool(raw_config.get("development", {}).get("skip_audit", False))
    started = time.perf_counter()
    pack = open_pack(REPO_ROOT / raw_config["index"]["directory"], verify="size" if skip else "files")
    sources = checkpoint_sources(model_config["repository"], model_config["revision"], declared_sha256=not skip)
    checkpoint_files = {key: entry.path for key, entry in sources.items()}
    verification = {}
    if not skip:
        for key, entry in sources.items():
            if key not in pack.files:
                verification[key] = sha256_file_direct(entry.path) == entry.sha256
    report["timings_ms"]["verify_files"] = (time.perf_counter() - started) * 1e3
    phase4b_index = json.loads((REPO_ROOT / raw_config["phase4b_reference"] / "index.json").read_text(encoding="utf-8"))
    report["verification"] = {
        "pack_files": "skipped (development run)" if skip else "against the Hub's sha256",
        "other_files": verification,
        "manifest_equals_phase4b": canonical_digest([pack.manifest]) == canonical_digest([phase4b_index["manifest"]]),
    }
    try:
        if not all(verification.values()) or not report["verification"]["manifest_equals_phase4b"]:
            fail("sources", report["verification"])
    except HardFailure:
        (output / "failure.json").write_text(json.dumps(failures, indent=2), encoding="utf-8")
        return 1

    groups = groups_from_pack(pack)
    profile.check_weights({name: segment.dtype for name, segment in pack.segments.items()})
    started = time.perf_counter()
    model, load_report = load_model_without_experts(model_config["repository"], model_config["revision"], dtype, device, checkpoint_files)
    report["timings_ms"]["load"] = (time.perf_counter() - started) * 1e3
    profile.check_model(model)
    adapter.check_config(model.config)
    report["load"] = {k: v for k, v in load_report.items() if k != "expert_parameters"}
    layer = target_layer_name(model, adapter, raw_config["target_layer"])
    report["target_layer"] = layer
    recorder = runtime.StepRecorder(model, adapter)
    capture = TargetCapture(model, adapter, layer)

    def on_call(call) -> None:
        recorder.on_call(call)
        capture.on_call(call)

    store_options = dict(
        direct=True, alignment=int(storage["alignment"]), max_gap=int(storage["max_gap"]), workers=int(storage["workers"]),
        max_read_bytes=int(storage["max_read_bytes"]), max_extent_bytes=int(storage["max_extent_bytes"]),
    )
    backend = MaterializationBackend(
        pack.store(**store_options), device, PageStreamer(device, int(storage["slot_bytes"]), int(storage["slots"]))
    )
    streamed = StreamedExperts(
        model, ExpertStore(WeightStore(backend), groups), compact=True, on_call=on_call, max_call_bytes=raw_config["call_budget_bytes"]
    ).install()

    # Phase 4B's reference records, for the steps of Phase 4B's own prompts (same token ids).
    reference_dir = REPO_ROOT / raw_config["phase4b_reference"]
    phase4b_prompts = {tuple(p["token_ids"]): p["prompt_id"] for p in read_jsonl(reference_dir / "prompts.jsonl")}
    phase4b_records = {(r["prompt_id"], r["step"]): r for r in read_jsonl(reference_dir / "reference.jsonl.gz")}
    samples: dict[str, list[torch.Tensor]] = {key: [] for key in (*TARGET_TENSORS, "top_k_index", "top_k_weights")}
    sample_ids: list[tuple[int, int]] = []
    compared = 0
    started_all = time.perf_counter()
    try:
        with JsonlWriter(output / "capture.jsonl.gz") as log:
            for prompt in prompts:
                old_id = phase4b_prompts.get(tuple(prompt["token_ids"]))
                timing = {}

                def before(step):
                    recorder.clear()
                    capture.clear()
                    torch.cuda.synchronize(device)
                    timing["start"] = time.perf_counter()

                def after(step, logits, positions, cache, prompt=prompt, old_id=old_id):
                    torch.cuda.synchronize(device)
                    elapsed = (time.perf_counter() - timing["start"]) * 1e3
                    record = runtime.step_record(prompt, step, positions, logits, cache, recorder)
                    values = capture.complete()
                    top = torch.topk(logits.float(), TOP_LOGITS)
                    record.update(
                        top_logits=top.values.tolist(),
                        top_ids=top.indices.tolist(),
                        target={key: tensor_digest(values[key]) for key in sorted(values)},
                        routed_target=sorted(values["top_k_index"].tolist()),
                        timings_ms={"step": elapsed},
                    )
                    nonlocal compared
                    expected = None if old_id is None else phase4b_records.get((old_id, step))
                    record["phase4b"] = None
                    if expected is not None:
                        verdict = runtime.compare(record, expected)
                        record["phase4b"] = {"prompt_id": old_id, **verdict}
                        compared += 1
                        if not all(verdict["matches"].values()):
                            fail("phase4b_mismatch", {"prompt_id": prompt["prompt_id"], "step": step, **verdict})
                    if step >= 1:
                        sample_ids.append((prompt["prompt_id"], step))
                        for key in samples:
                            samples[key].append(values[key])
                    log.write(record)

                runtime.decode(model, prompt["token_ids"], steps, device, before, after)
                print(f"capture: prompt {prompt['prompt_id']} ({prompt['length']} tokens) done", flush=True)
    except HardFailure:
        pass
    report["timings_ms"]["capture"] = (time.perf_counter() - started_all) * 1e3
    streamed.remove()
    capture.remove()
    backend.store.close()
    backend.streamer.close()
    tensors = {key: torch.stack(values).contiguous() for key, values in samples.items() if values}
    if sample_ids:
        tensors["prompt_id"] = torch.tensor([p for p, _ in sample_ids], dtype=torch.int64)
        tensors["step"] = torch.tensor([s for _, s in sample_ids], dtype=torch.int64)
        save_file(tensors, str(output / "capture.safetensors"), metadata={"target_layer": layer})
    report["samples"] = len(sample_ids)
    report["phase4b_compared_steps"] = compared
    report["memory"]["peak"] = process_memory()
    report["peak_device_bytes"] = torch.cuda.max_memory_allocated(device)
    (output / "capture_stage.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    if failures:
        (output / "failure.json").write_text(json.dumps(failures, indent=2), encoding="utf-8")
    return 1 if failures else 0


