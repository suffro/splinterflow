def shard_records(output: Path, name: str) -> list[dict]:
    """A part's records, its shards in order (`name`.0.jsonl.gz, `name`.1.jsonl.gz, ...)."""
    records, shard = [], 0
    while (output / f"{name}.{shard}.jsonl.gz").exists():
        records.extend(read_jsonl(output / f"{name}.{shard}.jsonl.gz"))
        shard += 1
    return records


def write_digest(output: Path) -> dict:
    def jsonl(name: str):
        path = output / name
        return canonical_digest(read_jsonl(path), EXCLUDED_FIELDS) if path.exists() else None

    capture = output / "capture.safetensors"
    samples, real_cells = shard_records(output, "samples"), shard_records(output, "real_cells")
    digest = {
        "prompts_sha256": canonical_digest(read_jsonl(output / "prompts.jsonl")),
        "capture_records_sha256": jsonl("capture.jsonl.gz"),
        "capture_tensors_sha256": sha256_file(capture) if capture.exists() else None,
        "samples_sha256": canonical_digest(samples, EXCLUDED_FIELDS) if samples else None,
        "real_cells_sha256": canonical_digest(real_cells, EXCLUDED_FIELDS) if real_cells else None,
        "excluded_fields": list(EXCLUDED_FIELDS),
    }
    (output / "digest.json").write_text(json.dumps(digest, indent=2), encoding="utf-8")
    return digest


def prepare(raw_config: dict, output: Path, args) -> None:
    runtime = phase4b()
    model_config, prompt_config = raw_config["model"], dict(raw_config["prompts"])
    if args.num_prompts is not None:
        prompt_config["lengths"] = prompt_config["lengths"][: args.num_prompts]
        raw_config["prompts"]["lengths"] = prompt_config["lengths"]
    if args.decode_steps is not None:
        raw_config["prompts"]["decode_steps"] = args.decode_steps
    if args.skip_audit:
        raw_config["development"] = {"skip_audit": True}
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(
        model_config["repository"], revision=model_config["tokenizer_revision"], trust_remote_code=bool(model_config["trust_remote_code_tokenizer"])
    )
    prompts, provenance = runtime.build_prompts(prompt_config, tokenizer)
    with open(output / "config.yaml", "w", encoding="utf-8") as handle:
        yaml.safe_dump(raw_config, handle, sort_keys=False)
    with JsonlWriter(output / "prompts.jsonl") as log:
        for prompt in prompts:
            log.write(prompt)
    environment = environment_metadata(
        REPO_ROOT,
        {"repository": model_config["repository"], "revision": model_config["revision"], "dtype": model_config["dtype"], "device": "cuda"},
        NUMERICS_FLAGS,
    )
    environment["tokenizer"] = {"class": type(tokenizer).__name__, "revision": model_config["tokenizer_revision"], "trust_remote_code": True}
    environment["prompts"] = provenance
    environment["num_prompts"] = len(prompts)
    environment["python_hash_seed"] = os.environ.get("PYTHONHASHSEED")
    environment["profile"] = runtime.load_adapter(model_config).REFERENCE_PROFILE.to_json()
    environment["started_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    (output / "environment.json").write_text(json.dumps(environment, indent=2), encoding="utf-8")
    print(f"prepared {output}: {len(prompts)} prompts, source tree {environment['source_tree_sha256'][:12]}")


STAGES = ("capture", "oracle", "oracle-real")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(REPO_ROOT / "configs" / "phase5a-expert-oracle.yaml"))
    parser.add_argument("--output", required=True)
    parser.add_argument("--stage", choices=["all", "prepare", *STAGES, "digest"], default="all")
    parser.add_argument("--num-prompts", type=int, default=None, help="use only the first N prompts (development)")
    parser.add_argument("--decode-steps", type=int, default=None, help="override the configured decode steps (development)")
    parser.add_argument("--skip-audit", action="store_true", help="skip the file verification (development; recorded)")
    parser.add_argument("--shard", type=int, default=0, help="the oracle stages' shard (oracle.shards in the config)")
    args = parser.parse_args()
    output = Path(args.output)
    if args.stage in STAGES:
        raw_config = yaml.safe_load((output / "config.yaml").read_text(encoding="utf-8"))
        prompts = read_jsonl(output / "prompts.jsonl")
        if args.stage == "capture":
            return run_capture(raw_config, output, prompts)
        return run_oracle(raw_config, output, prompts, "main" if args.stage == "oracle" else "real", args.shard)
    if args.stage == "digest":
        print(json.dumps(write_digest(output), indent=1))
        return 0
    if output.exists() and any(output.iterdir()):
        parser.error(f"{output} already exists and is not empty")
    output.mkdir(parents=True, exist_ok=True)
    raw_config = yaml.safe_load(Path(args.config).read_text(encoding="utf-8"))
    prepare(raw_config, output, args)
    if args.stage == "prepare":
        return 0
    command = [sys.executable, str(Path(__file__).resolve()), "--output", str(output)]
    shards = raw_config["oracle"]["shards"]
    for stage in STAGES:
        for shard in range(1 if stage == "capture" else int(shards["main" if stage == "oracle" else "real"])):
            started = time.perf_counter()
            code = subprocess.run([*command, "--stage", stage, "--shard", str(shard)], check=False).returncode
            print(f"stage {stage} shard {shard}: exit {code} after {time.perf_counter() - started:.0f}s", flush=True)
            if code:
                return code
    write_digest(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
