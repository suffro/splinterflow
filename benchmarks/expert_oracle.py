"""Phase 5A: AWPMI inside routed experts, an oracle study (decision 0009).

    PYTHONHASHSEED=<n> uv run python benchmarks/expert_oracle.py --output experiments/phase5a/<name> --stage <stage>

Stages (each in its own process; `all` runs them in turn):

  prepare  config, prompts (wikitext-2 as Phase 4B; its 16 prompts come first), environment
  capture  Moonlight on Shardraw's Phase 4B streamed path (configuration "stream": no cache, the call budget, under the
           device cap), after the published files are verified against the Hub's sha256. Per step it records every digest
           Phase 4B records (the steps of Phase 4B's prompts must equal Phase 4B's reference records), and at the target
           MoE layer's last position the oracle's inputs and the reference's values: x (the experts' input), the router's
           choice and weights, r (the residual), S (the shared experts), R (the routed experts' output), m (the MoE block),
           y (the layer's output), h (the final norm's output); per step the logits' sha256 and top values
  oracle   every sample: the reference recomputed from the captured inputs with the reference's own operations (checked
           against the capture bitwise: the exact fallback), the target weights checked against the Phase 4B reference's
           row digests; per arithmetic tier the ceiling (every routed weight read); the certified and rn_even tiers'
           cells (strategy × bound tier × ordering, `awpmi.oracle.experts.run_cell`) where their ceiling certifies
  oracle-real  the real tier's cells on the configured decode steps
  digest   sha256 of every output (timings excluded)

The oracle stages run in shards (blocks of prompts, `oracle.shards`), one process each, `--shard i`.

Writes, into the output directory:
  config.yaml, environment.json, prompts.jsonl
  capture.jsonl.gz        per prompt and step: digests, the token, the top logits, the Phase 4B comparison
  capture.safetensors     the decode samples' tensors at the target layer (not committed: regenerated by this stage;
                          its sha256 is in the digest)
  capture_stage.json      load report, verification, timings
  samples.<i>.jsonl.gz    per decode sample: checks, the reference's gap, ceilings per tier, cells (oracle stage, shard i)
  real_cells.<i>.jsonl.gz the real tier's cells (oracle-real stage, shard i)
  oracle_<part>_<i>_stage.json  strategies (storage multiplier, fallback bytes and modelled I/O), timings, peak memory
  digest.json             sha256 of prompts, capture records and tensors, samples and real cells
A stage stops at its first hard failure and saves it to failure.json.
"""

